#!/usr/bin/env bash
set -euo pipefail

output_dir=".macos-preferences"
raw_domains=()

usage() {
  cat <<'EOF'
Usage: scripts/export-macos-preferences.sh [--output DIR] [--raw-domain DOMAIN ...]

Export selected macOS preferences for review.

By default this writes a safe, allowlisted defaults script. Use --raw-domain to
also export complete domain plists for local review. Raw plists can contain
paths, account identifiers, recent items, device-specific values, and other
private state, so .macos-preferences is intentionally ignored by Git.

Examples:
  scripts/export-macos-preferences.sh
  scripts/export-macos-preferences.sh --raw-domain com.apple.universalaccess
EOF
}

while (($#)); do
  case "$1" in
    --output)
      output_dir="${2:-}"
      if [[ -z "$output_dir" ]]; then
        echo "--output requires a directory" >&2
        exit 2
      fi
      shift
      ;;
    --raw-domain)
      if [[ -z "${2:-}" ]]; then
        echo "--raw-domain requires a defaults domain" >&2
        exit 2
      fi
      raw_domains+=("$2")
      shift
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    *)
      echo "Unknown option: $1" >&2
      usage >&2
      exit 2
      ;;
  esac
  shift
done

if [[ "$(uname -s)" != "Darwin" ]]; then
  echo "Preference export requires macOS." >&2
  exit 1
fi

mkdir -p "$output_dir"

safe_script="$output_dir/current-defaults.sh"
cat >"$safe_script" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail

# Generated by scripts/export-macos-preferences.sh.
# Review before copying values into scripts/macos-defaults.sh.

EOF

append_default() {
  local domain="$1"
  local key="$2"
  local value
  local type

  if ! value="$(defaults read "$domain" "$key" 2>/dev/null)"; then
    return
  fi

  type="$(defaults read-type "$domain" "$key" 2>/dev/null || true)"

  case "$type" in
    "Type is boolean")
      if [[ "$value" == "1" ]]; then
        printf 'defaults write %q %q -bool true\n' "$domain" "$key" >>"$safe_script"
      else
        printf 'defaults write %q %q -bool false\n' "$domain" "$key" >>"$safe_script"
      fi
      ;;
    "Type is integer")
      printf 'defaults write %q %q -int %q\n' "$domain" "$key" "$value" >>"$safe_script"
      ;;
    "Type is float")
      printf 'defaults write %q %q -float %q\n' "$domain" "$key" "$value" >>"$safe_script"
      ;;
    "Type is string")
      printf 'defaults write %q %q -string %q\n' "$domain" "$key" "$value" >>"$safe_script"
      ;;
    *)
      printf '# Skipped %q %q: unsupported %s\n' "$domain" "$key" "${type:-type}" >>"$safe_script"
      ;;
  esac
}

safe_keys=(
  "NSGlobalDomain AppleInterfaceStyle"
  "NSGlobalDomain ApplePressAndHoldEnabled"
  "NSGlobalDomain InitialKeyRepeat"
  "NSGlobalDomain KeyRepeat"
  "NSGlobalDomain NSAutomaticCapitalizationEnabled"
  "NSGlobalDomain NSAutomaticDashSubstitutionEnabled"
  "NSGlobalDomain NSAutomaticPeriodSubstitutionEnabled"
  "NSGlobalDomain NSAutomaticQuoteSubstitutionEnabled"
  "NSGlobalDomain NSAutomaticSpellingCorrectionEnabled"
  "com.apple.dock autohide"
  "com.apple.dock mru-spaces"
  "com.apple.dock show-recents"
  "com.apple.dock tilesize"
  "com.apple.finder AppleShowAllFiles"
  "com.apple.finder FXEnableExtensionChangeWarning"
  "com.apple.finder FXPreferredViewStyle"
  "com.apple.finder ShowPathbar"
  "com.apple.finder ShowStatusBar"
  "com.apple.finder _FXShowPosixPathInTitle"
  "com.apple.screencapture show-thumbnail"
  "com.apple.screencapture type"
  "com.apple.screensaver askForPassword"
  "com.apple.screensaver askForPasswordDelay"
  "com.apple.universalaccess reduceTransparency"
)

for spec in "${safe_keys[@]}"; do
  append_default "${spec% *}" "${spec##* }"
done

chmod +x "$safe_script"

if ((${#raw_domains[@]})); then
  raw_dir="$output_dir/raw-plists"
  mkdir -p "$raw_dir"
  for domain in "${raw_domains[@]}"; do
    defaults export "$domain" "$raw_dir/$domain.plist"
  done
fi

cat <<EOF
Wrote $safe_script

Raw preference exports, if requested, are under $output_dir/raw-plists.
Review generated files before copying anything into committed dotfiles.
EOF
